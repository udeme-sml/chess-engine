    public static int Evaluate(Position position)
    {
        var score = 0;
        var board = position.Board;

        for (var sq = 0; sq < 64; sq++)
        {
            var piece = board[sq];
            if (piece == 0)
                continue;
            var pt = ChessConstants.GetPieceType(piece);
            var pstSq = ChessConstants.PieceColor(piece) == Color.White ? sq : sq ^ 56;
            score += MaterialValue[piece] + PstBonus[pt][pstSq];
        }

        return position.Stm == Color.White ? score : -score;
    }
