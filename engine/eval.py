def evaluate(position: Position) -> int:
    score = 0
    board = position.board

    for sq, piece in enumerate(board):
        if not piece:
            continue
        value = MATERIAL_VALUE[piece] + PST_BONUS[piece_type(piece)][sq] if piece_color(piece) == Color.WHITE else MATERIAL_VALUE[piece] + PST_BONUS[piece_type(piece)][sq ^ 56]
        score += value

    return score if position.stm == Color.WHITE else -score
